package provider

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"strings"
	"time"
)

type GeminiProvider struct {
	apiKey        string
	model         string
	httpClient    *http.Client
	baseURL       string
	allowLoopback bool
}

func NewGeminiProvider(apiKey string, model string) *GeminiProvider {
	if model == "" {
		model = "gemini-2.0-flash"
	}
	return &GeminiProvider{
		apiKey:     apiKey,
		model:      model,
		httpClient: NewSafeHTTPClient(60*time.Second, false),
		baseURL:    "https://generativelanguage.googleapis.com/v1beta",
	}
}

// NewGeminiProviderForTest creates a GeminiProvider allowing explicit loopback test servers (e.g. httptest.NewServer).
func NewGeminiProviderForTest(apiKey string, model string, baseURL string) *GeminiProvider {
	p := NewGeminiProvider(apiKey, model)
	p.baseURL = strings.TrimRight(baseURL, "/")
	p.allowLoopback = true
	p.httpClient = NewSafeHTTPClient(10*time.Second, true)
	return p
}

func (g *GeminiProvider) Name() string {
	return "google-gemini"
}

type geminiPart struct {
	Text string `json:"text"`
}

type geminiContent struct {
	Role  string       `json:"role"`
	Parts []geminiPart `json:"parts"`
}

type geminiSystemInstruction struct {
	Parts []geminiPart `json:"parts"`
}

type geminiRequest struct {
	Contents          []geminiContent          `json:"contents"`
	SystemInstruction *geminiSystemInstruction `json:"systemInstruction,omitempty"`
}

type geminiCandidate struct {
	Content struct {
		Parts []geminiPart `json:"parts"`
	} `json:"content"`
	FinishReason string `json:"finishReason"`
}

type geminiResponse struct {
	Candidates    []geminiCandidate `json:"candidates"`
	UsageMetadata struct {
		PromptTokenCount     int `json:"promptTokenCount"`
		CandidatesTokenCount int `json:"candidatesTokenCount"`
	} `json:"usageMetadata"`
	Error *struct {
		Message string `json:"message"`
		Code    int    `json:"code"`
	} `json:"error,omitempty"`
}

func (g *GeminiProvider) Complete(ctx context.Context, req Request) (*Response, error) {
	if g.apiKey == "" {
		return nil, fmt.Errorf("%w: GEMINI_API_KEY is not configured", ErrProviderFailed)
	}

	model := req.Model
	if model == "" {
		model = g.model
	}
	if err := ValidateModelName(model); err != nil {
		return nil, fmt.Errorf("%w: %w", ErrProviderFailed, err)
	}

	cleanBase, err := ValidateBaseURL(g.baseURL, g.allowLoopback, !g.allowLoopback)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrProviderFailed, err)
	}

	gReq := geminiRequest{
		Contents: make([]geminiContent, 0, len(req.Messages)),
	}

	if req.SystemPrompt != "" {
		gReq.SystemInstruction = &geminiSystemInstruction{
			Parts: []geminiPart{{Text: req.SystemPrompt}},
		}
	}

	for _, msg := range req.Messages {
		role := "user"
		if msg.Role == RoleAssistant {
			role = "model"
		}
		gReq.Contents = append(gReq.Contents, geminiContent{
			Role:  role,
			Parts: []geminiPart{{Text: msg.Content}},
		})
	}

	bodyBytes, err := json.Marshal(gReq)
	if err != nil {
		return nil, fmt.Errorf("gemini marshal error: %w", err)
	}

	endpoint := fmt.Sprintf("%s/models/%s:generateContent", cleanBase, model)
	httpReq, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(bodyBytes))
	if err != nil {
		return nil, fmt.Errorf("gemini request creation failed: %w", sanitizeTransportError(err))
	}
	httpReq.Header.Set("Content-Type", "application/json")
	httpReq.Header.Set("x-goog-api-key", g.apiKey)

	httpResp, err := g.httpClient.Do(httpReq)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrProviderFailed, sanitizeTransportError(err))
	}
	defer httpResp.Body.Close()

	respBytes, err := ReadBoundedBody(httpResp.Body, MaxUpstreamResponseBytes)
	if err != nil {
		return nil, fmt.Errorf("gemini read response failed: %w", err)
	}

	var gResp geminiResponse
	if err := json.Unmarshal(respBytes, &gResp); err != nil {
		return nil, fmt.Errorf("%w: %w", ErrInvalidResponse, err)
	}

	if gResp.Error != nil {
		return nil, fmt.Errorf("%w: API error (%d): %s", ErrProviderFailed, gResp.Error.Code, gResp.Error.Message)
	}

	if len(gResp.Candidates) == 0 || len(gResp.Candidates[0].Content.Parts) == 0 {
		return nil, fmt.Errorf("%w: no content generated by Gemini", ErrInvalidResponse)
	}

	var textParts []string
	for _, part := range gResp.Candidates[0].Content.Parts {
		textParts = append(textParts, part.Text)
	}

	return &Response{
		Content:      strings.Join(textParts, "\n"),
		Model:        model,
		FinishReason: gResp.Candidates[0].FinishReason,
		Usage: TokenUsage{
			InputTokens:  gResp.UsageMetadata.PromptTokenCount,
			OutputTokens: gResp.UsageMetadata.CandidatesTokenCount,
		},
	}, nil
}
